    def enable_automatic(self):
        """Retire old preview gates without recording a fabricated user approval."""
        lock=self.project.acquire()
        try:
            if self.state['status']=='running':raise ValueError('请等待当前任务结束')
            if self.automatic:return
            pending=self.state.get('pending');stage=self.state['stage']
            self.state['interaction_mode']='automatic'
            if stage in ('outline','sample') and (not pending or pending.get('checkpoint')):
                self.state['history'].append({'stage':stage,'output':copy.deepcopy(self.state['outputs'].get(stage)),
                    'pending':pending,'actor':'workflow_migration','at':now(),
                    'reason':'用户要求取消提纲/样稿确认，直接构建完整报告；不代表认可旧稿质量。'})
                self.state['stage']='writing' if self.state['outputs'].get('outline') else 'outline'
                self.state.update(status='ready',pending=None,approved_blocks=[])
                # A rejected preview is retained in history, never locked into the full draft.
                self.project.data.pop('writing_parts',None)
                self.project.data.pop('writing_draft',None)
                self.project.data.pop('report_design',None)
                for key in ('sample','sample_candidate'):
                    self.state['outputs'].pop(key,None)
                self.state.get('requirement_work',{}).pop('sample',None)
            self.project.save()
            self.debug_point('workflow','configured',details={'mode':'automatic','from_stage':stage})
        finally:lock.close()

    def debug_point(self,name,status,*,payload=None,result=None,details=None,elapsed=None):
        """Saved observations for developers, with no user gate or extra model call."""
        folder=self.project.root/'outputs/report-debug';folder.mkdir(parents=True,exist_ok=True)
        identity=uuid4().hex[:12]
        record={'id':identity,'at':now(),'stage':self.state['stage'],'name':name,'status':status,
            'trace':str(self.logger.path.relative_to(self.project.root)) if self.logger else None,
            'details':details or {}}
        if payload is not None:
            raw=json.dumps(payload,ensure_ascii=False,sort_keys=True,default=str).encode('utf-8')
            record['input']={'keys':list(payload),'sha256':hashlib.sha256(raw).hexdigest(),'bytes':len(raw),
                'field_bytes':{k:len(json.dumps(v,ensure_ascii=False,default=str).encode('utf-8')) for k,v in payload.items()},
                'notice':'完整角色输入在对应原始trace的消息中；此处不重复复制大材料。'}
        if result is not None:
            target=folder/f'{identity}-result.json';atomic_json(target,result)
            record['output']=str(target.relative_to(self.project.root))
        if elapsed is not None:record['elapsed_seconds']=round(elapsed,3)
        log=JsonlLogger(folder/'timeline.jsonl');log.log('report_debug_checkpoint',**record);log.close()
        atomic_json(folder/'latest.json',record)
        self.state['debug']={'latest':record,'timeline':str((folder/'timeline.jsonl').relative_to(self.project.root))}
        self.project.save()
        if self.logger:self.logger.log('report_debug_checkpoint',**record)

