    def part_result_package(self,spec):
        """Select by the agent's source plan, rather than a broad file category.

        The complete facts and originals remain addressable on disk. No claims
        are rewritten here, and this selection is not a new factual conclusion.
        """
        if active_design(self.project).get('card_selection_version') in CARD_SELECTION_VERSIONS:
            return self.selected_result_package(set(spec.get('card_ids',[])),spec.get('task_ids'),
                spec.get('detail_carriers',[]),fact_refs=set(spec['fact_refs']) if 'fact_refs' in spec else None)
        packet=self.result_package(spec.get('task_ids'),compact=True)
        text=' '.join(str(spec.get(k,'')) for k in ('focus','main_claim','evidence_choice'))
        known={s['id']:s for s in self.project.data['report_sources']}
        wanted=set(re.findall(r'\bS\d+\b',text))
        wanted.update(d['source_id'] for d in spec.get('detail_carriers',[]) if d.get('source_id') in known)
        for lo,hi in re.findall(r'\bS(\d+)\s*[-–—~～至到]+\s*S?(\d+)\b',text):
            if 0<=int(hi)-int(lo)<=len(known):
                wanted.update('S'+str(i).zfill(len(lo)) for i in range(int(lo),int(hi)+1))
        wanted.intersection_update(known)
        claims={c['id']:c for r in packet['results'].values() for c in r['analysis']['claims']}
        if wanted:
            chosen=[c for c in claims.values() if wanted.intersection(c.get('source_ids',[]))]
        else:
            words=set(re.findall(r'[A-Za-z0-9_-]{2,}|[\u4e00-\u9fff]{2,4}',text.lower()))
            def score(claim):
                raw=json.dumps(claim,ensure_ascii=False).lower()
                return sum(len(word) for word in words if word in raw)
            chosen=sorted(claims.values(),key=score,reverse=True)[:12]
        wanted.update(sid for c in chosen for sid in c.get('source_ids',[]) if sid in known)
        paths={known[sid]['path'] for sid in wanted}
        chosen_ids={c['id'] for c in chosen};assigned=set()
        for result in packet['results'].values():
            unique=[c for c in result['analysis']['claims'] if c['id'] in chosen_ids and c['id'] not in assigned]
            assigned.update(c['id'] for c in unique)
            result['analysis']['claims']=unique
            result['artifacts']=[a for a in result['artifacts'] if a['path'] in paths]
        packet['source_ids']=sorted(wanted)
        packet.pop('figure_outputs',None)  # Already supplied once in collaboration.
        packet['facts_archive']='project.json:report_workflow.outputs.facts; retrieve other originals with report_materials'
        return packet

