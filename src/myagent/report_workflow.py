    def validate_questions(self,result):
        questions=result.get('questions',[])
        if len(questions)>4:raise ValueError('每次最多4个关键问题')
        ids=[]
        for q in questions:
            if not isinstance(q,dict):raise ValueError('questions元素必须是含id/question/reason/suggestion的对象，不能是字符串；已答问题勿重问，无新问题用[]')
            if not all(q.get(k) for k in ('id','question','reason')):raise ValueError('问题需要id/question/reason')
            if 'blocking' in q and not isinstance(q['blocking'],bool):raise ProtocolError('questions.blocking','boolean',q['blocking'])
            ids.append(q['id'])
        if len(ids)!=len(set(ids)):raise ValueError('问题id不可重复')

    def validate_facts(self,result,*,allow_empty_claims=False):
        self.validate_questions(result)
