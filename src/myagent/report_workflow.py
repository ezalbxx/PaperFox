    def revise_document(self,stage,document,issues,validator,*,mode='requirements',locked=()):
        """Persist each small patch; a pause never replays accepted modifications."""
        p=self.project
        if mode=='paragraph_reflow':return self.reflow_paragraphs(stage,document,issues,validator,locked=locked)
        focused_edit = mode=='editing' and p.data.get('report_production_mode')=='lean'
        if (mode == 'editing' and len(document['sections']) > 1
                and len(json.dumps(document, ensure_ascii=False)) <= (70000 if p.data.get('report_architecture_version',1)>=2 else 18000)
                and sum(len(s['blocks']) for s in document['sections']) <= (220 if p.data.get('report_architecture_version',1)>=2 else 64)):
            revised = self.revise_whole_report(stage, document, issues, validator, locked)
            if revised is not None:
                return revised
        key=fingerprint({'stage':stage,'document':document,'issues':issues,'mode':mode,'context':CONTEXT_VERSION,
                         'composition_mode':'experimental' if self.experimental_revision else 'stable',
                         'facts':self.state['outputs'].get('facts'),
                         'section_policy':self.requirement_loop.packet(stage).get('section_policy')})
        folder=p.root/'outputs/report-edits';folder.mkdir(exist_ok=True)
        path=folder/f'{key}.json'
        if path.exists():
            work=json.loads(path.read_text(encoding='utf-8'))
            if work.get('deferred_units') and work['cursor']>=len(work['units']):
                # An explicit resume retries only the unresolved units against the
                # latest valid manuscript, never replays accepted patches.
                work['units']=[entry['spec'] for entry in work.pop('deferred_units')]
                work['cursor']=0
                atomic_json(path,work)
        else:
            if focused_edit:
                from .report_production_cost import repair_units
                from .report_section_policy import section_roles
                # Whole-report editing is optional. In the local fallback,
                # keep the Writer's draft except for located issues and synthesis.
                synthesis = [
                    b['id'] for s in document['sections'] if 'conclusion' in section_roles(s['heading'])
                    for b in s['blocks'] if b['type']=='text' and b['id'] not in locked
                ]
                priorities=list(issues)
                if synthesis:
                    priorities.append({'rule_id':'W02','severity':'soft','block_ids':synthesis,
                        'reason':'总结应收束全文，避免重复前文的操作和整组数据。',
                        'suggestion':'从已有观察提炼主要认识；已经做到时保持原文。'})
                prepared_units=repair_units(document,priorities) if priorities else []
                if self.logger:self.logger.log('report_edit_scope_selected',stage=stage,units=len(prepared_units))
            elif mode=='requirements' and issues and p.data.get('report_production_mode')=='lean':
                from .report_production_cost import repair_units
                prepared_units=repair_units(document,issues)
            else:
                units=document_units(document)
                assignments=assign_issues(units,issues) if issues else [[] for _ in units]
                prepared_units=[dict(u,issues=a) for u,a in zip(units,assignments) if a or mode=='editing']
            work={'source_hash':fingerprint(document),'document':copy.deepcopy(document),'cursor':0,
                'units':prepared_units}
            atomic_json(path,work)
        while work['cursor']<len(work['units']):
            index=work['cursor'];unit=work['units'][index]
            ids={b['id'] for b in unit['blocks'] if not focused_edit or b['type'] in ('text','heading')}
            current=work['document']
            blocks=[b for b in current['sections'][unit['section']]['blocks'] if b['id'] in ids]
            if not blocks:
                work['cursor']+=1;atomic_json(path,work)
                continue
            topics=topics_in(unit['subheading']+' '+json.dumps(unit['issues'],ensure_ascii=False))
            task_ids=list(dict.fromkeys(t for b in blocks for t in b.get('evidence',[])))
            parts=[part for section in p.data.get('report_design',{}).get('sections',[])
                if section['heading']==unit['heading'] for part in section['parts']]
            spec=next((part for part in parts if part['focus']==unit['subheading']),
                parts[0] if len(parts)==1 else {})
            if len(unit.get('subheadings',[]))>1:
                matched=[part for part in parts if part['focus'] in unit['subheadings']]
                spec={'focus':unit['subheading'],'parts':matched,
                    'card_ids':list(dict.fromkeys(cid for part in matched for cid in part.get('card_ids',[]))),
                    'detail_carriers':[carrier for part in matched for carrier in part.get('detail_carriers',[])],
                    **({'fact_refs':list(dict.fromkeys(ref for part in matched for ref in part['fact_refs']))}
                       if matched and all('fact_refs' in part for part in matched) else {}),
                    'task_ids':list(dict.fromkeys(t for part in matched for t in part.get('task_ids',[])))}
                task_ids=list(dict.fromkeys([*task_ids,*spec['task_ids']]))
            facts=self.part_result_package({**spec,'task_ids':task_ids,
                'focus':unit['subheading'] or unit['heading'],
                'main_claim':json.dumps(blocks,ensure_ascii=False)})
            section_blocks=current['sections'][unit['section']]['blocks']
            positions=[i for i,b in enumerate(section_blocks) if b['id'] in ids]
            neighbors=section_blocks[max(0,min(positions)-2):min(positions)]+section_blocks[max(positions)+1:max(positions)+3] if positions else []
            payload={'context_version':CONTEXT_VERSION,'mode':mode,
                **({'edit_scope':'focused_fallback','target_heading':unit['heading']} if focused_edit else {}),
                'adopted_figures':self.adopted_figures({'sections':[{'blocks':blocks}]}),
                'main_thread':p.data.get('report_design',{}).get('main_thread',''),
                'part_plan':{k:v for k,v in spec.items() if k in ('focus','question','task_ids')} if self.experimental_revision else spec,
                **({'original_source_excerpts':original_excerpts(p)} if self.experimental_revision else {}),
                'neighbor_blocks':[{'id':b['id'],'type':b['type'],'text':b.get('text','')[:800]} for b in neighbors],
                'candidate':{'title':current['title'],'sections':[{'heading':unit['heading'],'blocks':blocks}]},
                'editable_block_ids':sorted(ids),'locked_blocks':list(locked),
                'new_block_id_prefix':f'edit-{key[:8]}-u{index}-',
                'preserved_section_blocks':[{'id':b['id'],'type':b['type'],
                    'preview':str(b.get('text') or b.get('caption') or b.get('headers') or b.get('items') or '')[:180]}
                    for b in current['sections'][unit['section']]['blocks'] if b['id'] not in ids],
                'requirement_feedback':unit['issues'],
                'contract':compact_contract(self.requirement_loop.packet(stage,topics)),
                'human_decisions':self.human_decisions(),'evidence':facts,
                'report_map':[{'heading':s['heading'],'topics':[b.get('text','') for b in s['blocks'] if b.get('type')=='heading']} for s in current['sections']]}
            def validate(result):
                patches=result.get('patches')
                if not isinstance(patches,list):raise ValueError('需要patches数组')
                if len(json.dumps(patches,ensure_ascii=False))>18000:raise ValueError('本轮仅提交局部差异，补丁过长')
                updated=apply_local_patches(current,patches,ids,locked)
                if mode=='editing':
                    from .report_section_policy import preserve_result_tables
                    preserve_result_tables(current,updated)
                validator(updated)
            try:
                result=self.role('report_patcher',STRUCTURE_EDIT if stage=='structure' else PATCH,payload,validate,task_id=f'patch:{key[:12]}:{index}:{len(blocks)}')
            except StageUnresolved as exc:
                self.defer_recovery(stage,exc,recovery_path=str(path),unit_key=sorted(ids),heading=unit['heading'])
                work.setdefault('deferred_units',[]).append({'unit':index,'kind':exc.kind,'reason':exc.reason,
                    'candidate':exc.candidate,'spec':unit})
                work['cursor']+=1;atomic_json(path,work)
                continue
            except OutputTruncated:
                if len(blocks)<=1:
                    if not focused_edit:raise
                    error=StageUnresolved('protocol','局部编辑未返回完整补丁，保留该段已有稿。')
                    self.defer_recovery(stage,error,recovery_path=str(path),unit_key=sorted(ids),heading=unit['heading'])
                    work.setdefault('deferred_units',[]).append({'unit':index,'kind':error.kind,'reason':error.reason,
                        'candidate':None,'spec':unit})
                    work['cursor']+=1;atomic_json(path,work)
                    continue
                middle=len(blocks)//2
                children=[dict(unit,blocks=blocks[:middle]),dict(unit,blocks=blocks[middle:])]
                assignments=assign_issues(children,unit['issues'])
                work['units'][index:index+1]=[dict(u,issues=a) for u,a in zip(children,assignments) if a or (mode=='editing' and not focused_edit)]
                atomic_json(path,work)
                if self.logger:self.logger.log('report_edit_split',stage=stage,cursor=index,blocks_before=len(blocks))
                continue
            work['document']=apply_local_patches(current,result['patches'],ids,locked)
            self.resolve_recovery(stage,recovery_path=str(path),unit_key=sorted(ids))
            work['cursor']+=1
            atomic_json(path,work)
            self.state['progress']={'label':'修订图文' if mode=='requirements' else '整理正文',
                'completed':work['cursor'],'total':len(work['units']),'topic':unit['subheading'] or unit['heading']}
            p.save()
        return work['document']

    def sample_target(self,outline):
        description=outline['sample_focus'];targets=[(i,j,part) for i,s in enumerate(outline['sections']) for j,part in enumerate(s['parts'])]
        exact=[t for t in targets if t[2]['focus']==description]
        if len(exact)==1:return exact[0]
        terms=set(re.findall(r'Q\d+',description))
        scored=[]
        for target in targets:
            i,_,part=target;heading=outline['sections'][i]['heading']
            heading_match=heading in description
            term_count=sum(term in part['focus'] for term in terms)
            if heading_match or term_count:scored.append((int(heading_match)*10+term_count,target))
        scored.sort(key=lambda row:row[0],reverse=True)
        if scored and (len(scored)==1 or scored[0][0]>scored[1][0]):return scored[0][1]
        raise ValueError('样稿目标必须唯一对应提纲部分，不能默认改写为其他章节；请在sample_focus使用准确focus或明确章节与题号')

