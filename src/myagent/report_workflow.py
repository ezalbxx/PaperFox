    def resolve_recovery(self, stage, **scope):
        """Close only the same saved operation, leaving unrelated failures visible."""
        for record in self.state.get('deferred_recoveries', []):
            if record['stage']==stage and record['status']=='open' and all(record.get(k)==v for k,v in scope.items()):
                record.update(status='resolved',resolved_at=now())
                if self.logger:self.logger.log('report_recovery_resolved',**record)
        self.project.save()

    def check_limits(self):
        budget=self.state.get('budget')
