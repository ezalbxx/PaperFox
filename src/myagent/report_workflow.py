    def topic_evidence(self,topic,sources):
        """Deterministic evidence views, never developer-written report conclusions."""
        packet={'topic':topic,'origin':'Extracted original lines/events, not a new experiment or model summary.',
            'sources':[],'omitted_ids':[]};size=0
        tool=ReportMaterials(self.project)
        for source in sources:
            path=self.project.file(source['path']);name=path.name.lower();category=source['category']
            if path.suffix.lower() in ('.png','.jpg','.jpeg','.svg','.pdf','.npy','.npz','.pkl','.pt','.pth','.xlsx','.zip'):
                packet['sources'].append({'id':source['id'],'path':source['path'],'label':source.get('label'),
                    'notice':'Binary/image material; use appropriate viewer, not text decoding.'})
                continue
            if category=='performance' and not (name in ('summary.json','summary.csv','summarize_v9.py') or name.endswith('.quality_manual.json')):continue
            if category=='source' and name=='package.json':continue
            if category=='statistics' and name in ('summary.json','registry_final_v3.json','usage_per_call.csv','context_growth.csv'):continue
            view={'id':source['id'],'path':source['path'],'sha256':source['sha256'] if 'sha256' in source else digest(path)}
            if path.suffix.lower() in ('.zst','.zstd'):
                import zstandard
                with path.open('rb') as f,zstandard.ZstdDecompressor().stream_reader(f) as r:
                    lines=io.TextIOWrapper(r,encoding='utf-8').read().splitlines()
                events=[];kinds={}
                for number,line in enumerate(lines,1):
                    event=json.loads(line);kind=event.get('type','');data=event.get('data',{})
                    if kind=='assistant/message':
                        msg=data.get('message',{})
                        texts=[{'pointer':f'/data/message/content/{i}/text','text':b['text'][:9000],
                            'total_chars':len(b['text'])} for i,b in enumerate(msg.get('content',[]))
                            if b.get('type')=='text' and b.get('text')]
                        if texts:events.append({'line':number,'type':kind,'seq':event.get('seq'),'id':msg.get('id'),
                            'turn':data.get('turn'),'step':data.get('step'),'usage':data.get('usage'),'texts':texts})
                    elif kind in ('session','request/context','tool/call','tool/result','turn/end'):
                        count=kinds.get(kind,0);kinds[kind]=count+1
                        if count<(1 if kind in ('session','request/context') else 3):
                            events.append({'line':number,'type':kind,'original_excerpt':line[:1800],
                                'total_chars':len(line),'data_keys':list(data) if isinstance(data,dict) else []})
                view.update(total_lines=len(lines),line_unit='decoded physical lines',events=events)
            elif category=='source' and path.suffix=='.js':
                lines=path.read_text(encoding='utf-8-sig').splitlines()
                symbols=[f'{i}: {line[:180]}' for i,line in enumerate(lines,1)
                    if re.search(r'\b(?:function|class)\s+\w+|(?:async\s+)?\w+\([^;]*\)\s*\{',line)]
                view.update(total_lines=len(lines),symbol_index=symbols[:100],notice='Symbol index only; read original body to verify implementation.')
            else:
                read=json.loads(tool.run({'operation':'read','id':source['id'],'start_line':1,
                    'end_line':26 if name=='summarize_v9.py' else 160},None).output)
                view.update({k:read[k] for k in ('total_lines','start_line','excerpt','line_unit') if k in read})
            length=len(json.dumps(view,ensure_ascii=False))
            if size+length>115000:
                packet['omitted_ids'].append(source['id']);continue
            size+=length;packet['sources'].append(view)
        return packet

