class ReportMaterials:
    name='report_materials'
    description='Read original report materials. search query retrieves original content with page/line anchors from mixed library. list category/query paginates inventory. read id (S ID or exact registered project path)/start_line/end_line or page (PDF), optional JSON pointer/start_char; read_many up to 6. events indexes original JSONL events. No execution. Images metadata only.'
    parameters={'type':'object','properties':{'operation':{'type':'string','enum':['list','search','read','read_many','events']},
        'category':{'type':'string'},'query':{'type':'string'},'id':{'type':'string'},
        'event_type':{'type':'string'},
        'page':{'type':'integer'},'start_line':{'type':'integer'},'end_line':{'type':'integer'},'start_char':{'type':'integer'},'pointer':{'type':'string'},
        'requests':{'type':'array','minItems':1,'maxItems':6,'items':{'type':'object','properties':{
            'id':{'type':'string'},'page':{'type':'integer'},'start_line':{'type':'integer'},'end_line':{'type':'integer'},
            'start_char':{'type':'integer'},'pointer':{'type':'string'}},'required':['id']}}},'required':['operation']}

    def __init__(self,project):
        self.project=project

    def run(self,args,ctx):
        sources=list(self.project.data['report_sources'])
        # The same M ids accepted by the contract must also be readable by the tool.
        sources.extend({'id':m['id'],'category':'documents','label':m['name'],
                        'path':m['path'],'sha256':m.get('sha256'),'role':m['role']}
            for m in self.project.data['materials'] if m['role'] in ('guidance','template')
            and m['id'] not in {s['id'] for s in sources})
        if args['operation']=='search':
            from .report_library import search
            if not self.project.data.get('material_library'):
                rows=[s for s in sources if args.get('query','').lower() in (s['path']+' '+s.get('label','')).lower()
                    and (not args.get('category') or s['category']==args['category'])]
                return ToolResult(output=json.dumps({'matches':rows[:20],'notice':'Legacy project: filename search only; read originals by id.'},ensure_ascii=False))
            return ToolResult(output=json.dumps(search(self.project,args.get('query',''),args.get('category')),ensure_ascii=False))
        if args['operation']=='read_many':
            requests=args.get('requests',[])
            if not 1<=len(requests)<=6:raise ValueError('read_many requires 1–6 source requests')
            results=[]
            for request in requests:
                try:
                    value=json.loads(self.run({**request,'operation':'read'},ctx).output)
                    excerpt=value.get('excerpt','')
                    if value.get('chunks'):
                        remaining=3000;clipped=[]
                        for chunk in value['chunks']:
                            if remaining<=0:break
                            clipped.append({**chunk,'text':chunk['text'][:remaining]})
                            remaining-=len(clipped[-1]['text'])
                        value['chunks']=clipped;value['truncated']=True
                    if len(excerpt)>3000:
                        value['excerpt']=excerpt[:3000]+'\n[batch excerpt truncated; use read for the needed original lines]'
                        value['truncated']=True
                    results.append({k:v for k,v in value.items() if k in ('id','category','path','total_lines','start_line','excerpt','line_unit','notice','truncated','width','height','pointer','start_char','chunks')})
                except (KeyError,StopIteration,ValueError,OSError) as exc:
                    results.append({'id':request.get('id'),'error':f'{type(exc).__name__}: {exc}'})
            return ToolResult(output=json.dumps({'results':results},ensure_ascii=False))
        if args['operation']=='list':
            rows=[s for s in sources if (not args.get('category') or s['category']==args['category'])
                and args.get('query','').lower() in (s['path']+' '+s.get('label','')).lower()]
            offset=max(0,args.get('start_line',1)-1)
            value={'total':len(rows),'sources':rows[offset:offset+60],
                'next_start_line':offset+61 if len(rows)>offset+60 else None}
        else:
            identifier = args.get('id', '')
            item = next((s for s in sources if s['id'] == identifier), None)
            normalize = lambda value: os.path.normcase(str(value).replace('\\', '/'))
            if item is None:
                matches = [s for s in sources if normalize(s['path']) == normalize(identifier)]
                if len(matches) == 1:
                    item = matches[0]
            if item is None:
                candidates = [s for s in sources if Path(s['path']).name == Path(identifier).name][:4]
                hints = '; '.join(s['id'] + '=' + s['path'] for s in candidates)
                raise ValueError('未找到登记材料ID或完整登记路径：' + str(identifier)
                                 + ('；候选：' + hints if hints else '；先用list/search取得真实S编号'))
            path=self.project.file(item['path'])
            if path.suffix.lower() in ('.pdf','.doc','.docx'):
                from .report_library import passages
                chunks=[];size=0
                for piece in passages(path,self.project.root/"extracted"):
                    if args.get('page') and piece.get('page')!=args['page']:continue
                    if path.suffix.lower() in ('.doc','.docx') and piece.get('start_char',0)+len(piece['text'])<=args.get('start_char',0):continue
                    if size+len(piece['text'])>16000:break
                    chunks.append(piece);size+=len(piece['text'])
                return ToolResult(output=json.dumps({'id':item['id'],'path':item['path'],'chunks':chunks,
                    'notice':'Original document text with PDF page anchors; not a visual inspection.'},ensure_ascii=False))
            if path.suffix.lower() in ('.png','.jpg','.jpeg'):
                from PIL import Image
                with Image.open(path) as im:
                    value={**item,'width':im.width,'height':im.height,'notice':'Image metadata only; view the image to inspect its actual pixels.'}
                capture=next((c for c in ReportRequirements(self.project).captures() if c['id']==item['id']),None)
                if capture:value['capture']=capture
            else:
                if path.suffix.lower() in ('.zstd','.zst'):
                    import zstandard
                    with path.open('rb') as f,zstandard.ZstdDecompressor().stream_reader(f) as stream:
                        lines=io.TextIOWrapper(stream,encoding='utf-8').read().splitlines()
                else:
                    lines=path.read_text(encoding='utf-8-sig',errors='replace').splitlines()
                start=max(1,int(args.get('start_line',1)));end=min(len(lines),int(args.get('end_line',start+79)),start+159)
                if args['operation']=='events':
                    rows=[];cursor=start
                    event_type=args.get('event_type','assistant/message')
                    for number in range(start,len(lines)+1):
                        cursor=number+1
                        try:event=json.loads(lines[number-1])
                        except json.JSONDecodeError:continue
                        if event.get('type')!=event_type:continue
                        data=event.get('data',{});message=data.get('message',{})
                        texts=[{'pointer':f'/data/message/content/{index}/text','chars':len(block.get('text','')),
                            'preview':block.get('text','')[:700]} for index,block in enumerate(message.get('content',[]))
                            if isinstance(block,dict) and block.get('type')=='text' and block.get('text')]
                        if event_type=='assistant/message' and not texts:continue
                        rows.append({'line':number,'type':event_type,'seq':event.get('seq'),
                            'id':message.get('id'),'turn':data.get('turn'),'step':data.get('step'),
                            'usage':data.get('usage'),'text':texts})
                        if len(rows)>=12:break
                    return ToolResult(output=json.dumps({'id':item['id'],'total_lines':len(lines),'events':rows,
                        'next_start_line':cursor if cursor<=len(lines) else None,'line_unit':'decoded physical lines'},ensure_ascii=False))
                excerpt=[];size=0
                for number in range(start,end+1):
                    line=lines[number-1]
                    if 'pointer' in args:
                        selected=json.loads(line)
                        for part in args['pointer'].strip('/').split('/') if args['pointer'] else []:
                            key=part.replace('~1','/').replace('~0','~')
                            selected=selected[int(key)] if isinstance(selected,list) else selected[key]
                        line=json.dumps(selected,ensure_ascii=False)
                    line=line[max(0,int(args.get('start_char',0))):]
                    clipped=line[:10000]+(' [line truncated]' if len(line)>10000 else '')
                    if size+len(clipped)>20000:break
                    excerpt.append(f'{number}: {clipped}');size+=len(clipped)
                value={**item,'total_lines':len(lines),'start_line':start,'excerpt':'\n'.join(excerpt),
                    'line_unit':'decoded physical lines' if path.suffix.lower() in ('.zstd','.zst') else 'physical lines',
                    'notice':'Original historical experiment material, not a new run.'}
                for key in ('pointer','start_char'):
                    if key in args:value[key]=args[key]
        return ToolResult(output=json.dumps(value,ensure_ascii=False))


class ReportWorkflow(LabPipeline):
    """Stage checkpoints persist across processes, user replies stay explicit."""
    def __init__(self,project,**kwargs):
        kwargs={**REPORT_LIMITS,**kwargs}
        super().__init__(project,**kwargs)
        self.report_collaboration=True
        if 'report_workflow' not in project.data:
            project.data['report_architecture_version']=ARCHITECTURE_VERSION
            project.data['report_workflow']={'stage':'intake','status':'ready','outputs':{},'history':[],
                'interactions':[],'pending':None,'approved_blocks':[],'interaction_mode':'automatic'}
            project.save()

    def editing_input(self):
        preview=self.state.get('interrupted_preview',{})
        if preview.get('resume_document_path') and not preview.get('resumed_into_version'):
            path=self.project.file(preview['resume_document_path'])
            if digest(path)!=preview['resume_document_sha256']:
                raise ValueError('编辑恢复源发生变化；保留断点，不自动换成预览稿重做')
            return json.loads(path.read_text(encoding='utf-8'))
        return self.project.data['report']['document']

    def writing_order(self,design):
        return production_order(design) if self.project.data.get('report_architecture_version',1)>=2 else range(len(design['sections']))

    def normalize_stage_result(self, name, payload, result):
        result = copy.deepcopy(result)
        for index, question in enumerate(result.get('questions', [])):
            if isinstance(question, dict):question.setdefault('id', f'q{index+1}')
        if name == 'report_story_cards' and isinstance(result.get('experiments'),list):
            result['card_selection_version'] = CARD_SELECTION_VERSION
        if name == 'report_designer' and isinstance(result.get('sections'),list):
            result.setdefault('writing_plan_version', 1)
            if self.project.data.get('report_architecture_version',1)>=2:
                result['card_selection_version'] = CARD_SELECTION_VERSION
            card_packet=self.state['outputs'].get('story_cards',{})
            curated=card_packet.get('mode')=='curated_facts'
            entries=card_entry_index(card_packet) if curated else {}
            for section in result.get('sections', []):
                for part in section.get('parts', []):
                    if curated:
                        refs=part.pop('owned_fact_refs',part.get('fact_refs',[]))
                        part['fact_refs']=refs
                        if isinstance(refs,list):
                            part['card_ids']=list(dict.fromkeys(entries[ref] for ref in refs
                                if isinstance(ref,str) and ref in entries))
                    part.setdefault('character_budget', 1000)
                    part.setdefault('detail_carriers', [])
            # Derive routing for curated facts; preserve accepted legacy ownership.
            cards = self.state['outputs'].get('story_cards', {}).get('experiments', [])
            if curated:result['content_ownership']=[]
            owners = result.setdefault('content_ownership', [])
            from .report_section_policy import section_roles
            for card in cards:
                existing = [o for o in owners if o.get('card_id') == card['id']]
                if len(existing)>1:continue  # Ambiguous ownership must be returned to the planner.
                assigned = [s for s in result.get('sections', []) if any(
                    card['id'] in part.get('card_ids', []) for part in s.get('parts', []))]
                owner = existing[0] if existing else {'card_id': card['id']}
                for role, field in [('procedure','procedure_section'),('results','result_section'),('analysis','analysis_section')]:
                    if field in owner:continue
                    choices = [s['heading'] for s in assigned if role in section_roles(s['heading'])]
                    if curated and assigned:owner[field]=(choices or [s['heading'] for s in assigned])[0]
                    elif len(choices) == 1:owner[field] = choices[0]
                    elif len(assigned) == 1:owner[field] = assigned[0]['heading']
                if not existing and len(owner) == 4:owners.append(owner)
        if name == 'writer':
            prefix = payload.get('block_id_prefix')
            for section in result.get('sections', []):
                for index, block in enumerate(section.get('blocks', [])):
                    if prefix and not block.get('id'):block['id'] = prefix + f'b{index+1}'
                    normalize_block_sample_names(block)
        if name == 'report_figures':
            for figure in result.get('figures', []):
                if 'caption' in figure:
                    figure['caption'] = normalize_sample_names(figure['caption'])
        if name == 'report_patcher':
            for patch in result.get('patches', []):
                if isinstance(patch.get('block'), dict):
                    normalize_block_sample_names(patch['block'])
        return result

    @staticmethod
    def blocking_questions(result):
        return [q for q in result.get('questions', []) if q.get('blocking', True)]

    def defer_recovery(self, stage, error, **details):
        record = {'stage': stage, 'kind': error.kind, 'reason': error.reason, 'status':'open', **details}
        self.state.setdefault('deferred_recoveries', []).append(record)
        if self.logger:self.logger.log('report_recovery_deferred', **record)
