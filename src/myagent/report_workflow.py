    def review_edited_chapters(self,document):
        """Reuse unchanged chapter judgments; review edited chapters locally."""
        p=self.project;current=copy.deepcopy(document);records=[]
        specs={s['heading']:s for s in p.data.get('report_design',{}).get('sections',[])}
        previous=copy.deepcopy(p.data.get('writing_draft'))
        try:
            for index,section in enumerate(current['sections']):
                chapter={'title':current['title'],'sections':[section]}
                old=self.state.get('chapter_reviews',{}).get(str(index),{})
                if old.get('status')=='passed' and old.get('draft')==chapter:
                    records.append({'heading':section['heading'],'status':'reused_unchanged'});continue
                # Include actual current preceding prose, not the pre-edit draft.
                p.data['writing_draft']=current
                fixed=self.review_chapter(chapter,section_index=index,
                    section_spec=specs.get(section['heading'],{'heading':section['heading'],'parts':[]}))
                current['sections'][index]=fixed['sections'][0]
                entry=self.state.get('chapter_reviews',{}).get(str(index),{})
                if entry.get('status')=='passed':self.resolve_recovery('chapter_review',heading=section['heading'])
                records.append({'heading':section['heading'],'status':entry.get('status','reviewed')})
                self.state['outputs']['editing_candidate']={'document':copy.deepcopy(current),'post_review_cursor':index+1}
                p.save()
        finally:
            if previous is None:p.data.pop('writing_draft',None)
            else:p.data['writing_draft']=previous
            self.state['outputs']['post_edit_chapter_reviews']={'scope':'chapters','chapters':records,
                'whole_report_review_run':False};p.save()
        return current

